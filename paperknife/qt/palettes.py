"""
paperknife.qt.palettes
The colour palettes of the Qt interface: plain data, one dict per palette,
role name -> (light, dark).  A colour is "#RRGGBB" or "#AARRGGBB" (Qt's
HexArgb, alpha first).

theme.py reads the active palette (env PK_PALETTE, default "today";
theme.apply_palette(name) at run time).  Two kinds of role:

- APP roles: read by paperknife's own code (theme.color / hex_color / pair,
  style sheets it writes, QPainter code) and used as they are.
- FLUENT roles: colours QFluentWidgets draws by itself (its .qss files and
  its paint code).  fluent_route.py gives every library colour a role and
  moves it by exactly as much as that role moved from "today", so the
  library's own shading between states (rest / hover / pressed) is kept and
  the role's reference value is drawn exactly.  Under "today" nothing moves.

ROLES says where each role reaches the screen.

CANDIDATES (generated, between the GENERATED markers) are the phase 6 colour
scorer's shortlist (phase6/colour/candidates.json), mapped onto these roles by
phase6/colour/to_app_palettes.py: the scorer's 24 roles directly, the rest
tone-on-tone from an anchor scorer role at today's OKLCH offset.  MICA names
the palettes whose window role is Mica's solid fallback (Mica stays on).
"""
